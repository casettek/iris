#!/usr/bin/env python3
"""Write the Unicode general-category table the tekken text split reads.

    python3 scripts/gen-unicode-classes.py > crates/prompt-core/src/unicode_classes.rs

The table is part of how a `mistral-dense` prompt becomes tokens, so it is
committed rather than taken from whatever library a build links. It holds the
categories the split's pattern names: the five letter categories, marks and
numbers. Everything else is `OTHER`.
"""
import sys
import unicodedata

CLASSES = {"Lu": "UPPER", "Ll": "LOWER", "Lt": "TITLE", "Lm": "MODIFIER", "Lo": "OTHER_LETTER"}


def class_of(code):
    category = unicodedata.category(chr(code))
    if category in CLASSES:
        return CLASSES[category]
    if category[0] == "M":
        return "MARK"
    if category[0] == "N":
        return "NUMBER"
    return None


ranges = []
start = previous = None
for code in range(0x110000):
    current = class_of(code)
    if current != previous:
        if previous is not None:
            ranges.append((start, code - 1, previous))
        start, previous = code, current
if previous is not None:
    ranges.append((start, 0x10FFFF, previous))

out = sys.stdout
out.write("//! Unicode general categories, generated by `scripts/gen-unicode-classes.py`.\n")
out.write(f"//! Unicode {unicodedata.unidata_version}. Do not edit by hand.\n\n")
out.write("pub const OTHER: u8 = 0;\npub const UPPER: u8 = 1;\npub const LOWER: u8 = 2;\n")
out.write("pub const TITLE: u8 = 3;\npub const MODIFIER: u8 = 4;\npub const OTHER_LETTER: u8 = 5;\n")
out.write("pub const MARK: u8 = 6;\npub const NUMBER: u8 = 7;\n\n")
out.write("/// `(first, last, class)` for every run of code points with a class, in order.\n")
out.write(f"pub const RANGES: [(u32, u32, u8); {len(ranges)}] = [\n")
for first, last, name in ranges:
    out.write(f"    (0x{first:X}, 0x{last:X}, {name}),\n")
out.write("];\n")
